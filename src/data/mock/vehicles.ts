const FUEL_WORD: Record<FuelType, LocalizedText> = {
  petrol: { en: "petrol", bn: "পেট্রোল" },
  diesel: { en: "diesel", bn: "ডিজেল" },
  hybrid: { en: "petrol hybrid", bn: "পেট্রোল হাইব্রিড" },
  phev: { en: "petrol plug-in hybrid", bn: "পেট্রোল প্লাগ-ইন হাইব্রিড" },
  ev: { en: "electric", bn: "ইলেকট্রিক" },
};

const BN_DIGITS = "০১২৩৪৫৬৭৮৯";
const bnDigits = (s: string) => s.replace(/\d/g, (d) => BN_DIGITS[Number(d)]);

function engineDescription(cc: number, fuel: FuelType, cylinders?: number): LocalizedText {
  const litres = (cc / 1000).toFixed(1);
  const cyl = cylinders ? { en: `, ${cylinders}-cylinder`, bn: `, ${bnDigits(String(cylinders))} সিলিন্ডার` } : { en: "", bn: "" };
  return {
    en: `${litres} L ${FUEL_WORD[fuel].en}${cyl.en}`,
    bn: `${bnDigits(litres)} লিটার ${FUEL_WORD[fuel].bn}${cyl.bn}`,
  };
}

function buildSpecs(s: Seed): SpecGroup[] {
  const x = s.extras;
  const item = (key: SpecKey, value: SpecItem["value"] | undefined, unit?: Unit): SpecItem[] =>
    value === undefined || value === "" ? [] : [{ key, value, ...(unit ? { unit } : {}) }];

  const groups: SpecGroup[] = [
    {
      group: "powertrain",
      items: [
        ...(s.engine ? item("engineType", engineDescription(s.engine.displacementCc, s.fuelType, x.cylinders)) : []),
        ...item("displacement", s.engine?.displacementCc, "cc"),
        ...item("enginePower", s.engine?.powerHp, "hp"),
        ...item("engineTorque", s.engine?.torqueNm, "Nm"),
        ...item("motorPower", s.motor?.powerKw, "kW"),
        ...item("motorTorque", s.motor?.torqueNm, "Nm"),
      ],
    },
    {
      group: "performance",
      items: [
        ...item("topSpeed", x.topSpeedKmh, "kmh"),
        ...item("acceleration", x.accelS, "s"),
        ...item("fuelEconomy", s.efficiency.kmPerLitre, "kmPerL"),
        ...item("energyConsumption", s.efficiency.kWhPer100km, "kWhPer100km"),
        ...item("fuelPerHour", s.efficiency.litresPerHour, "lPerHour"),
      ],
    },
    {
      group: "battery",
      items: s.battery
        ? [
            ...item("batteryCapacity", s.battery.capacityKwh, "kWh"),
            ...item(s.fuelType === "phev" ? "electricRange" : "range", s.battery.rangeKm, "km"),
            ...item("acCharge", x.acKw, "kW"),
            ...item("dcCharge", s.battery.dcFastChargeKw, "kW"),
            ...item("dcChargeTime", x.dcMinutes, "min"),
            ...(s.battery.warrantyYears
              ? item("batteryWarranty", {
                  en: `${s.battery.warrantyYears} years (manufacturer terms apply)`,
                  bn: `${bnDigits(String(s.battery.warrantyYears))} বছর (নির্মাতার শর্ত প্রযোজ্য)`,
                })
              : []),
          ]
        : [],
    },
    {
      group: "dimensions",
      items: [
        ...item("length", x.lengthMm, "mm"),
        ...item("width", x.widthMm, "mm"),
        ...item("height", x.heightMm, "mm"),
        ...item("wheelbase", x.wheelbaseMm, "mm"),
        ...item("groundClearance", x.groundClearanceMm, "mm"),
        ...item("kerbWeight", x.kerbKg, "kg"),
      ],
    },
    {
      group: "capacity",
      items: [
        ...item("seats", s.seats, "seats"),
        ...item("fuelTank", x.tankL, "L"),
        ...item("bootSpace", x.bootL, "L"),
        ...item("payload", x.payloadKg, "kg"),
        ...item("grossWeight", x.gvwKg, "kg"),
        ...item("towing", x.towingKg, "kg"),
      ],
    },
    {
      group: "chassis",
      items: [...item("tyres", x.tyres), ...item("turningRadius", x.turningRadiusM, "m"), ...item("emissions", x.emissions)],
    },
    {
      group: "work",
      items: [...item("ptoPower", x.ptoHp, "hp"), ...item("liftCapacity", x.liftKg, "kg"), ...item("forwardGears", x.gears)],
    },
  ];
  return groups.filter((g) => g.items.length > 0);
}

const VIEW_WORDS: Record<MediaView, LocalizedText> = {
  front34: { en: "front three-quarter view", bn: "সামনের কোণ থেকে" },
  side: { en: "side profile", bn: "পাশ থেকে" },
  rear34: { en: "rear three-quarter view", bn: "পেছনের কোণ থেকে" },
  interior: { en: "interior and dashboard", bn: "ভেতরের অংশ ও ড্যাশবোর্ড" },
  detail: { en: "working detail", bn: "কাজের অংশের ক্লোজ-আপ" },
};

function buildImages(s: Seed): Media[] {
  const brand = brands.find((b) => b.id === s.brandId)!;
  const views: MediaView[] =
    s.category === "tractor" || s.bodyType === "truck"
      ? ["front34", "side", "rear34", "detail"]
      : ["front34", "side", "rear34", "interior"];
  return views.map((view) => ({
    // Add real photos under /public/media/vehicles/<slug>/ and set `src` here (or from the API).
    alt: {
      en: `${brand.name.en} ${s.model} ${s.variant}, ${VIEW_WORDS[view].en}`,
      bn: `${brand.name.bn} ${s.model} ${s.variant}, ${VIEW_WORDS[view].bn}`,
    },
    aspect: "16/10",
    view,
  }));
}

function vehicle(s: Seed): Vehicle {
  const { n, extras, features, safety, ...rest } = s;
  void extras;
  return {
    ...rest,
    id: `v${String(n).padStart(2, "0")}`,
    reference: `EU-${1000 + n}`,
    features: features.map((id) => featureCatalogue[id]),
    safety: safety.map((id) => safetyCatalogue[id]),
    specs: buildSpecs(s),
    images: buildImages(s),
  };
}

